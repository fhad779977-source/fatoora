export const BLANK_TEMPLATE = { id: "blank" as const, icon: FileText };

export function getTemplate(id: string) {
  return TEMPLATES.find((t) => t.id === id);
}

export function documentFromTemplate(id: TemplateId, fallbackTitle: string, locale: "ar" | "en" = "ar"): MidadDocument {
  const tpl = getTemplate(id);
  if (!tpl) return createDocument({ title: fallbackTitle, language: locale });
  return createDocument({ title: tpl.title, language: "ar", theme: tpl.theme(), blocks: tpl.blocks(), templateId: tpl.id });
}
